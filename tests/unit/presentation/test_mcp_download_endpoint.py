"""The browser can redeem a capability without exposing it in an HTTP URL."""

import asyncio
import io
from pathlib import Path
from typing import cast

from fastapi import FastAPI
import pytest
from starlette.testclient import TestClient

from src.application.services.mcp.download_capability import DownloadTarget, DownloadUnavailable
from src.infrastructure.adapters.security.encryption import FileEncryptionService
from src.infrastructure.adapters.storage.minio_storage_adapter import MinioFileStorageAdapter
from src.presentation.api.dependencies.mcp_download import get_mcp_download_capabilities
from src.presentation.api.dependencies.download_stream import iter_decrypted_object
from src.presentation.api.dependencies.service_dependencies import get_encryption_service, get_minio_download_adapter
from src.presentation.api.routers.v1.mcp_download import router


class Service:
    async def redeem(self, capability):
        if capability != "valid":
            raise DownloadUnavailable()
        return DownloadTarget("job", 7, "output/report.pdf", "grant")


class Storage:
    def __init__(self, data):
        self.data = data
        self.stream = None

    def get_object_stream(self, key):
        assert key == "output/report.pdf"
        self.stream = io.BytesIO(self.data)
        return self.stream


def client(storage, encryption):
    app = FastAPI()
    app.include_router(router)
    app.dependency_overrides[get_mcp_download_capabilities] = lambda: Service()
    app.dependency_overrides[get_minio_download_adapter] = lambda: storage
    app.dependency_overrides[get_encryption_service] = lambda: encryption
    return TestClient(app)


def test_browser_page_and_plaintext_download() -> None:
    storage = Storage(b"PDF document")
    with client(storage, None) as c:
        page = c.get("/api/v1/mcp/download#not-sent-to-server")
        assert page.status_code == 200 and page.headers["cache-control"] == "no-store"
        assert "#" not in str(page.request.url)
        script = c.get("/api/v1/mcp/download/script.js")
        assert "history.replaceState" in script.text
        response = c.post("/api/v1/mcp/download/redeem", data={"capability": "valid"})
        assert response.status_code == 200
        assert response.content == b"PDF document"
        assert response.headers["content-disposition"].startswith("attachment;")
        assert response.headers["cache-control"] == "no-store"
        assert storage.stream is not None and storage.stream.closed
        assert c.post("/api/v1/mcp/download/redeem", data={"capability": "bad"}).status_code == 404


def test_encrypted_output_is_streamed_as_plaintext(tmp_path: Path) -> None:
    encryption = FileEncryptionService(allow_autogenerated_key=True)
    source = tmp_path / "input"
    encrypted = tmp_path / "encrypted"
    source.write_bytes(b"plaintext conversion output" * 10000)
    encryption.encrypt_file_to(source, encrypted, "7")
    storage = Storage(encrypted.read_bytes())
    with client(storage, encryption) as c:
        response = c.post("/api/v1/mcp/download/redeem", data={"capability": "valid"})
        assert response.status_code == 200
        assert response.content == source.read_bytes()
        assert storage.stream is not None and storage.stream.closed


def test_missing_key_never_yields_ciphertext(tmp_path: Path) -> None:
    encryption = FileEncryptionService(allow_autogenerated_key=True)
    source, encrypted = tmp_path / "input", tmp_path / "encrypted"
    source.write_bytes(b"private")
    encryption.encrypt_file_to(source, encrypted, "7")
    storage = Storage(encrypted.read_bytes())

    async def read():
        return [
            part async for part in iter_decrypted_object(
                cast(MinioFileStorageAdapter, storage), "output/report.pdf", None, "7"
            )
        ]

    with pytest.raises(RuntimeError):
        asyncio.run(read())
    assert storage.stream is not None and storage.stream.closed
